private fun medicineKey(name: String) = name.trim().lowercase(Locale.ROOT).replace("®", "").replace("™", "").replace(Regex("\\s+"), " ").trim()
private val medicineCatalog = catalogRecords.groupBy { medicineKey(it.name) }.mapNotNull { (key, records) ->
    if (records.map { medicineKey(it.inn) }.distinct().size == 1) key to records.first() else null
}.toMap()
internal fun knownMedicine(name: String): KnownMedicine? = medicineCatalog[medicineKey(name)]
internal data class InnDraft(val value: String = "", val automatic: Boolean = true) {
    fun forName(name: String) = if (automatic) copy(value = knownMedicine(name)?.inn ?: "") else this
    fun edited(value: String) = InnDraft(value, false)
}
