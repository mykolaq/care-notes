package com.carenotes.app

import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.result.contract.ActivityResultContracts
import android.util.Base64
import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.os.PersistableBundle
import androidx.compose.foundation.layout.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.text.input.PasswordVisualTransformation
import androidx.compose.ui.unit.dp
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import org.json.JSONObject

@Composable internal fun FamilySettings(activity: MainActivity, dismiss: () -> Unit, changed: () -> Unit) {
    val sync = remember { FamilySync(activity) }
    var connected by remember { mutableStateOf(sync.connected) }
    var status by remember { mutableStateOf(sync.status) }
    var busy by remember { mutableStateOf(false) }
    var error by remember { mutableStateOf<String?>(null) }
    var certificate by remember { mutableStateOf("") }
    var certificateFingerprint by remember { mutableStateOf("") }
    var url by remember { mutableStateOf("") }
    var secret by remember { mutableStateOf("") }
    var code by remember { mutableStateOf("") }
    var name by remember { mutableStateOf(android.os.Build.MODEL.take(80)) }
    var editable by remember { mutableStateOf(true) }
    var accepted by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf<String?>(null) }
    var recovery by remember { mutableStateOf(false) }
    var devices by remember { mutableStateOf<List<JSONObject>>(emptyList()) }
    var revoke by remember { mutableStateOf<JSONObject?>(null) }
    var disconnect by remember { mutableStateOf(false) }
    var conflictChoice by remember { mutableStateOf<Boolean?>(null) }
    val scope = rememberCoroutineScope()
    fun work(action: () -> Unit) {
        busy = true; error = null
        scope.launch {
            val result = withContext(Dispatchers.IO) { runCatching(action) }
            busy = false; connected = sync.connected; status = sync.status
            result.onFailure { error = it.message ?: "Не удалось выполнить действие" }
            changed()
        }
    }
    val certificatePicker = rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { uri ->
        if (uri != null) work {
            val bytes = activity.contentResolver.openInputStream(uri)?.use { it.readNBytes(16385) } ?: error("Не удалось открыть сертификат")
            val parsed = SyncTls.parse(bytes)
            val value = Base64.encodeToString(parsed.encoded, Base64.NO_WRAP or Base64.URL_SAFE)
            val fingerprint = SyncTls.fingerprint(parsed.encoded)
            withContextSafe { certificate = value; certificateFingerprint = fingerprint }
        }
    }
    FormDialog("Семейный доступ", { if (!busy) dismiss() }) {
        if (!connected) {
            Text("Синхронизация необязательна. Без подключения всё хранится на этом телефоне.")
            Text("Для подключения нужен подготовленный сервер с HTTPS. Настройки защиты входа задаются отдельно на каждом устройстве.")
            Field("Название этого устройства", name, { name = it.take(80) })
            HorizontalDivider()
            Text("Подключиться по приглашению", style = MaterialTheme.typography.titleMedium)
            OutlinedTextField(code, { code = it.take(8192) }, label = { Text("Код приглашения или восстановления") }, visualTransformation = PasswordVisualTransformation(), modifier = Modifier.fillMaxWidth(), enabled = !busy)
            Row(verticalAlignment = Alignment.CenterVertically) { Checkbox(accepted, { accepted = it }, enabled = !busy); Text("При доступе только для просмотра местные записи будут заменены семейными. Копии документов останутся на сервере и устройствах семьи.", Modifier.weight(1f)) }
            Button(onClick = { val value=code; val deviceName=name; work { sync.join(value, deviceName) }; code = "" }, enabled = !busy && code.isNotBlank() && accepted && name.isNotBlank(), modifier = Modifier.fillMaxWidth()) { Text("Подключить устройство") }
            HorizontalDivider()
            Text("Первое подключение семьи", style = MaterialTheme.typography.titleMedium)
            Field("Адрес сервера: https://IP:8443", url, { url = it })
            Text("Для сервера по IP выберите care-root.crt, полученный с вашей VPS. Сертификат передаётся родственникам вместе с приглашением.")
            OutlinedButton(onClick = { certificatePicker.launch(arrayOf("*/*")) }, enabled = !busy) { Text("Выбрать сертификат сервера") }
            if (certificate.isNotEmpty()) {
                Text("SHA-256: $certificateFingerprint", style = MaterialTheme.typography.bodySmall)
                TextButton(onClick = { certificate = ""; certificateFingerprint = "" }, enabled = !busy) { Text("Убрать сертификат") }
            }
            OutlinedTextField(secret, { secret = it.take(512) }, label = { Text("Секрет первого подключения") }, visualTransformation = PasswordVisualTransformation(), modifier = Modifier.fillMaxWidth(), enabled = !busy)
            Button(onClick = { val u=url; val s=secret; val n=name; val cert=certificate; work { sync.connectOwner(u,s,n,cert) }; secret="" }, enabled = !busy && url.isNotBlank() && secret.isNotBlank() && name.isNotBlank(), modifier = Modifier.fillMaxWidth()) { Text("Создать семейный доступ") }
        } else {
            Text("Доступ: ${when(sync.role) { "owner" -> "владелец"; "editor" -> "просмотр и редактирование"; else -> "только просмотр" }}")
            Text(status)
            Text("Назначения, посещения и документы шифруются до отправки. Время и включение напоминаний настраиваются отдельно на каждом телефоне.")
            Button(onClick = { work { sync.sync() } }, enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Обновить сейчас") }
            if (activity.getSharedPreferences("family_sync", Context.MODE_PRIVATE).getBoolean("conflict", false)) {
                Text("Одна запись изменена на двух устройствах. Выберите версию только для конфликтующих записей. Остальные изменения объединятся.")
                OutlinedButton(onClick = { conflictChoice = true }, enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Оставить изменения этого телефона") }
                OutlinedButton(onClick = { conflictChoice = false }, enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Принять изменения из семьи") }
            }
            if (sync.role == "owner") {
                HorizontalDivider()
                Row(verticalAlignment = Alignment.CenterVertically) { Checkbox(editable, { editable = it }, enabled = !busy); Text("Разрешить редактирование новому устройству") }
                Button(onClick = { work { val value = sync.invite(editable); withContextSafe { generated = value; recovery = false } } }, enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Создать приглашение на 10 минут") }
                OutlinedButton(onClick = { work { val array = sync.devices(); val result = (0 until array.length()).map { array.getJSONObject(it) }; withContextSafe { devices = result } } }, enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Подключённые устройства") }
                devices.forEach { device ->
                    Text("${device.getString("name")} · ${when(device.getString("role")) { "owner" -> "владелец"; "editor" -> "редактирование"; else -> "просмотр" }}")
                    if (device.getString("role") != "owner") TextButton(onClick = { revoke = device }, enabled = !busy) { Text("Закрыть доступ") }
                }
            }
            OutlinedButton(onClick = { work { val value = sync.recovery(); withContextSafe { generated = value; recovery = true } } }, enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Сохранить код восстановления") }
            Text("Храните код восстановления отдельно от телефона: он содержит ключ данных и доступ этого устройства. Код владельца позволяет управлять семейным доступом.")
            TextButton(onClick = { disconnect = true }, enabled = !busy) { Text("Отключить синхронизацию на этом телефоне") }
        }
        if (busy) LinearProgressIndicator(Modifier.fillMaxWidth())
        error?.let { Text(it, color = MaterialTheme.colorScheme.error) }
        TextButton(onClick = dismiss, enabled = !busy) { Text("Закрыть") }
    }
    generated?.takeIf { LocalUnlocked.current }?.let { value ->
        AlertDialog(onDismissRequest = { generated = null }, title = { Text(if(recovery) "Код восстановления" else "Приглашение готово") }, text = {
            Text(if(recovery) "Скопируйте и сохраните код в надёжном месте. Он даёт доступ к данным. Не отправляйте его посторонним." else "Скопируйте код и передайте родственнику. Код действует 10 минут, используется один раз и содержит ключ семейных данных.")
        }, confirmButton = { TextButton(onClick = {
            val clip = ClipData.newPlainText("Семейный доступ", value)
            clip.description.extras = PersistableBundle().apply { putBoolean("android.content.extra.IS_SENSITIVE", true) }
            (activity.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager).setPrimaryClip(clip)
            generated = null
        }) { Text("Скопировать") } }, dismissButton = { TextButton(onClick = { generated = null }) { Text("Закрыть") } })
    }
    revoke?.takeIf { LocalUnlocked.current }?.let { device -> AlertDialog(onDismissRequest = { revoke = null }, title = { Text("Закрыть доступ?") }, text = { Text("${device.getString("name")} больше не сможет загружать и отправлять данные. Уже полученные копии останутся на устройстве; ключ шифрования не меняется.") }, confirmButton = { TextButton(onClick = { revoke = null; work { sync.revoke(device.getString("id")); withContextSafe { devices = emptyList() } } }) { Text("Закрыть доступ") } }, dismissButton = { TextButton(onClick = { revoke = null }) { Text("Отмена") } }) }
    if (disconnect && LocalUnlocked.current) AlertDialog(onDismissRequest = { disconnect = false }, title = { Text("Отключить синхронизацию?") }, text = { Text("Записи останутся на телефоне. Серверный доступ устройства сохранится до его отзыва владельцем. Перед отключением сохраните код восстановления, особенно если это устройство владельца.") }, confirmButton = { TextButton(onClick = { disconnect = false; work { sync.disconnect() } }) { Text("Отключить") } }, dismissButton = { TextButton(onClick = { disconnect = false }) { Text("Отмена") } })
    conflictChoice?.takeIf { LocalUnlocked.current }?.let { choice -> AlertDialog(onDismissRequest = { conflictChoice = null }, title = { Text("Выбрать версию записей?") }, text = { Text(if(choice) "В конфликтующих записях сохранятся изменения этого телефона. Изменения других устройств в этих записях будут заменены." else "В конфликтующих записях сохранятся изменения семьи. Несохранённые на сервере изменения этого телефона в этих записях будут заменены.") }, confirmButton = { TextButton(onClick = { conflictChoice = null; work { sync.sync(choice) } }) { Text("Подтвердить выбор") } }, dismissButton = { TextButton(onClick = { conflictChoice = null }) { Text("Отмена") } }) }
}

// State callbacks execute on the main thread even when the network operation is on IO.
private fun withContextSafe(action: () -> Unit) { android.os.Handler(android.os.Looper.getMainLooper()).post(action) }
